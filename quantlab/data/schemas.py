"""Canonical market-data domain schemas (spec sections 5.2 and 5.5).

Precision decisions (see docs/data_dictionary/daily-bars.md):
- Prices are `Decimal` with at most 6 decimal places, stored as Decimal(20, 6).
- Turnover is `Decimal` with at most 4 decimal places, stored as Decimal(24, 4).
- Volume is a whole number of shares, stored as a 64-bit integer.
Values with more precision than this are quarantined, never rounded silently.
"""

from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field

# Bump when the canonical daily-bar schema changes. Part of the ingestion fingerprint.
DAILY_BAR_SCHEMA_VERSION = "1"

PRICE_DECIMAL_PLACES = 6
TURNOVER_DECIMAL_PLACES = 4

SOURCE_ID_PATTERN = r"^[a-z][a-z0-9_]{1,62}$"


class Exchange(StrEnum):
    NSE = "NSE"
    BSE = "BSE"


class InstrumentType(StrEnum):
    EQUITY = "EQUITY"
    ETF = "ETF"
    INDEX = "INDEX"


class Currency(StrEnum):
    INR = "INR"


class AdjustmentBasis(StrEnum):
    """Corporate-action adjustment status of the prices in a dataset. Always explicit."""

    UNADJUSTED = "UNADJUSTED"
    SPLIT_ADJUSTED = "SPLIT_ADJUSTED"
    SPLIT_AND_DIVIDEND_ADJUSTED = "SPLIT_AND_DIVIDEND_ADJUSTED"
    # The supplier of the data does not know. Allowed, but always raises a quality warning.
    UNKNOWN = "UNKNOWN"


class DataClassification(StrEnum):
    # Generated by code for development and tests. Never real market data and never
    # allowed in performance claims (spec section 15).
    SYNTHETIC_TEST_DATA = "SYNTHETIC_TEST_DATA"
    # A file the user supplied and is responsible for having the right to use.
    USER_SUPPLIED = "USER_SUPPLIED"
    # Retrieved from a provider under a licence referenced in the manifest.
    LICENSED = "LICENSED"


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class SymbolMapping(_Frozen):
    """One effective-dated display identity of an instrument. Dates are inclusive."""

    symbol: str
    name: str | None
    isin: str | None
    valid_from: date
    valid_to: date | None
    source_id: str


class Instrument(_Frozen):
    """Stable internal identity. Symbols, names and ISINs live on `SymbolMapping`."""

    instrument_id: str
    exchange: Exchange
    instrument_type: InstrumentType
    currency: Currency
    symbols: tuple[SymbolMapping, ...] = ()

    def symbol_as_of(self, as_of: date) -> SymbolMapping | None:
        for mapping in self.symbols:
            if mapping.valid_from <= as_of and (
                mapping.valid_to is None or as_of <= mapping.valid_to
            ):
                return mapping
        return None


class DailyBar(_Frozen):
    instrument_id: str
    exchange: Exchange
    trading_date: date
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: int
    turnover: Decimal | None
    source_id: str
    source_record_id: str | None
    retrieved_at: datetime
    source_as_of: datetime | None
    currency: Currency
    adjustment_basis: AdjustmentBasis
    schema_version: str


class QuarantinedRecord(_Frozen):
    """A source record that failed validation. Kept visible, never silently dropped."""

    source_record_id: str | None
    provider_instrument_id: str | None
    reasons: tuple[str, ...]
    raw_fields: dict[str, str | None]


class FileChecksum(_Frozen):
    path: str
    sha256: str
    byte_size: int


class RawObjectRef(_Frozen):
    kind: str
    format_id: str
    sha256: str
    byte_size: int
    path: str
    retrieved_at: datetime
    source_as_of: datetime | None = None


class InstrumentGap(_Frozen):
    instrument_id: str
    missing_weekdays: int


class SnapshotManifest(_Frozen):
    """Everything needed to identify, verify and reproduce a dataset snapshot (spec 5.5)."""

    snapshot_id: str
    dataset_id: str
    version: int
    source_id: str
    provider_name: str
    licence_reference: str
    data_classification: DataClassification
    source_dataset_version: str
    extracted_at: datetime
    created_at: datetime
    first_trading_date: date | None
    last_trading_date: date | None
    instrument_ids: tuple[str, ...]
    record_count: int
    quarantined_count: int
    schema_version: str
    normalizer_version: str
    adjustment_basis: AdjustmentBasis
    adjustment_methodology: str
    input_fingerprint: str
    content_sha256: str
    files: tuple[FileChecksum, ...]
    raw_objects: tuple[RawObjectRef, ...]
    # Weekdays with no bar between an instrument's first and last bar. Includes exchange
    # holidays, because no licensed trading calendar is integrated yet.
    weekday_gaps: tuple[InstrumentGap, ...]
    quality_warnings: tuple[str, ...] = Field(default=())
