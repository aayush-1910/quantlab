"""SYNTHETIC_TEST_DATA provider.

Generates a deterministic random walk for a few made-up instruments. It exists so the
ingestion pipeline can be developed and tested without licensed data. The output is not
market data: it must never be mixed with real data or used in any performance claim
(spec section 15). Every symbol, name and manifest it produces says so.
"""

import json
import random
from datetime import date, timedelta
from decimal import Decimal

from quantlab.data.providers.base import (
    KIND_DAILY_BARS,
    KIND_INSTRUMENTS,
    ProviderDataError,
    ProviderInfo,
    ProviderInstrument,
    ProviderSymbol,
    RawBarRecord,
    RawPayload,
)
from quantlab.data.schemas import (
    AdjustmentBasis,
    Currency,
    DataClassification,
    Exchange,
    InstrumentType,
)

SYNTHETIC_LABEL = "SYNTHETIC_TEST_DATA"
SYNTHETIC_SOURCE_ID = "synthetic_fixture"
SYNTHETIC_FORMAT_ID = "synthetic-json-v1"
GENERATOR_VERSION = "1"

_CENT = Decimal("0.01")


def _encode(document: dict[str, object]) -> bytes:
    return json.dumps(document, sort_keys=True, separators=(",", ":")).encode("utf-8")


class SyntheticFixtureProvider:
    def __init__(
        self,
        start: date = date(2024, 1, 1),
        end: date = date(2024, 3, 29),
        instrument_count: int = 3,
        seed: int = 7,
    ) -> None:
        if end < start:
            raise ValueError("end must not be before start")
        if not 1 <= instrument_count <= 999:
            raise ValueError("instrument_count must be between 1 and 999")
        self._start = start
        self._end = end
        self._instrument_count = instrument_count
        self._seed = seed

    @property
    def info(self) -> ProviderInfo:
        return ProviderInfo(
            source_id=SYNTHETIC_SOURCE_ID,
            provider_name=f"{SYNTHETIC_LABEL} generator",
            licence_reference="Not applicable: generated by quantlab, not market data",
            data_classification=DataClassification.SYNTHETIC_TEST_DATA,
            source_dataset_version=(
                f"generator-{GENERATOR_VERSION}/seed-{self._seed}/n-{self._instrument_count}/"
                f"{self._start.isoformat()}..{self._end.isoformat()}"
            ),
            adjustment_basis=AdjustmentBasis.UNADJUSTED,
            adjustment_methodology=(
                "Synthetic random walk. There are no corporate actions, so no adjustment applies."
            ),
        )

    def _ids(self) -> list[str]:
        return [f"SYNTH{n:03d}" for n in range(1, self._instrument_count + 1)]

    def fetch_instruments(self) -> RawPayload:
        instruments = [
            {
                "provider_instrument_id": pid,
                "exchange": Exchange.NSE.value,
                "instrument_type": InstrumentType.EQUITY.value,
                "symbol": pid,
                "name": f"{SYNTHETIC_LABEL} instrument {pid}",
                "valid_from": self._start.isoformat(),
            }
            for pid in self._ids()
        ]
        return RawPayload(
            kind=KIND_INSTRUMENTS,
            format_id=SYNTHETIC_FORMAT_ID,
            content=_encode({"label": SYNTHETIC_LABEL, "instruments": instruments}),
            file_extension="json",
        )

    def fetch_daily_bars(self) -> RawPayload:
        bars: list[dict[str, str]] = []
        for index, pid in enumerate(self._ids()):
            rng = random.Random(f"{self._seed}:{pid}")  # noqa: S311 - fixture data, not security
            close = Decimal(100 * (index + 1))
            day = self._start
            while day <= self._end:
                if day.weekday() < 5:
                    open_ = close
                    change = Decimal(rng.randint(-300, 300)) / Decimal(10000)
                    close = max((open_ * (1 + change)).quantize(_CENT), _CENT)
                    high = max(open_, close) + Decimal(rng.randint(0, 100)) * _CENT
                    low = max(min(open_, close) - Decimal(rng.randint(0, 100)) * _CENT, _CENT)
                    volume = rng.randint(10_000, 500_000)
                    typical = ((high + low + close) / 3).quantize(_CENT)
                    bars.append(
                        {
                            "provider_instrument_id": pid,
                            "trading_date": day.isoformat(),
                            "open": str(open_),
                            "high": str(high),
                            "low": str(low),
                            "close": str(close),
                            "volume": str(volume),
                            "turnover": str(typical * volume),
                        }
                    )
                day += timedelta(days=1)
        return RawPayload(
            kind=KIND_DAILY_BARS,
            format_id=SYNTHETIC_FORMAT_ID,
            content=_encode({"label": SYNTHETIC_LABEL, "bars": bars}),
            file_extension="json",
        )


def _load(content: bytes, key: str) -> list[dict[str, object]]:
    try:
        document = json.loads(content)
    except ValueError as exc:
        raise ProviderDataError(f"synthetic payload is not valid JSON: {exc}") from exc
    if not isinstance(document, dict) or document.get("label") != SYNTHETIC_LABEL:
        raise ProviderDataError(f"synthetic payload is missing the {SYNTHETIC_LABEL} label")
    rows = document.get(key)
    if not isinstance(rows, list) or not all(isinstance(row, dict) for row in rows):
        raise ProviderDataError(f"synthetic payload has no '{key}' list")
    return rows


class SyntheticParser:
    def parse_instruments(self, content: bytes) -> list[ProviderInstrument]:
        instruments = []
        for row in _load(content, "instruments"):
            try:
                instruments.append(
                    ProviderInstrument(
                        provider_instrument_id=str(row["provider_instrument_id"]),
                        exchange=Exchange(str(row["exchange"])),
                        instrument_type=InstrumentType(str(row["instrument_type"])),
                        currency=Currency.INR,
                        symbols=(
                            ProviderSymbol(
                                symbol=str(row["symbol"]),
                                name=str(row["name"]),
                                isin=None,
                                valid_from=date.fromisoformat(str(row["valid_from"])),
                                valid_to=None,
                            ),
                        ),
                    )
                )
            except (KeyError, ValueError) as exc:
                raise ProviderDataError(f"invalid synthetic instrument {row!r}: {exc}") from exc
        return instruments

    def parse_daily_bars(self, content: bytes) -> list[RawBarRecord]:
        records = []
        for index, row in enumerate(_load(content, "bars")):
            fields = {key: None if value is None else str(value) for key, value in row.items()}
            provider_instrument_id = fields.pop("provider_instrument_id", None)
            records.append(
                RawBarRecord(
                    source_record_id=f"bars[{index}]",
                    provider_instrument_id=provider_instrument_id,
                    fields=fields,
                )
            )
        return records
